"""Independent test-only ISO BMFF Common Encryption producer.

The clear MP4 is generated by the existing encoder. Its sample bytes and BMFF
encryption metadata are transformed here with Cryptodome, independently of the
production FFmpeg demuxer. This deliberately small fixture format has a final
moov box, one sample description per track, H.264 length-prefixed NALs and AAC.
It covers per-sample 16-byte IVs, NAL subsamples, and CTR/CBC pattern variants;
it is not a general-purpose MP4 writer or a DRM licensing implementation.
"""
from __future__ import annotations

import json
from pathlib import Path
import struct
import subprocess

from Cryptodome.Cipher import AES


def _box(kind: bytes, content: bytes) -> bytes:
    return struct.pack('>I4s', 8+len(content), kind)+content


def _boxes(data: bytes):
    position=0
    while position<len(data):
        assert position+8<=len(data)
        size,kind=struct.unpack_from('>I4s',data,position)
        assert 8<=size<=len(data)-position
        yield kind,data[position+8:position+size]
        position+=size
    assert position==len(data)


def _regions(sample: bytes, video: bool, scheme: str):
    if video:
        position=0
        parts=[]
        while position<len(sample):
            length=int.from_bytes(sample[position:position+4], 'big')
            assert 0<length<=len(sample)-position-4
            parts.append((5,length-1))
            position+=4+length
    else:
        parts=[(0,len(sample))]
    if scheme!='cbc1':
        return parts
    aligned=[]
    carry=0
    for clear,protected in parts:
        aligned.append((carry+clear,protected//16*16))
        carry=protected%16
    if carry:
        aligned.append((carry,0))
    return aligned


def _encrypt(sample: bytes, *, key: bytes, iv: bytes, scheme: str, video: bool):
    regions=_regions(sample,video,scheme)
    transformed=bytearray(sample)
    ctr=AES.new(key,AES.MODE_CTR,nonce=b'',initial_value=int.from_bytes(iv,'big'))
    cbc=AES.new(key,AES.MODE_CBC,iv=iv)
    position=0
    for clear,protected in regions:
        position+=clear
        if scheme=='cenc':
            transformed[position:position+protected]=ctr.encrypt(sample[position:position+protected])
        elif scheme=='cbc1':
            transformed[position:position+protected]=cbc.encrypt(sample[position:position+protected])
        else:
            # cbcs resets the CBC IV for each NAL protected region; cens keeps
            # the CTR counter across regions. Neither advances through skips.
            region_cbc=AES.new(key,AES.MODE_CBC,iv=iv)
            step=160 if video else 16
            for offset in range(0,protected,step):
                if protected-offset<16:
                    break
                at=position+offset
                cipher=ctr if scheme=='cens' else region_cbc
                transformed[at:at+16]=cipher.encrypt(sample[at:at+16])
        position+=protected
    assert position==len(sample)
    metadata=iv+struct.pack('>H',len(regions))+b''.join(struct.pack('>HI',clear,protected) for clear,protected in regions)
    return bytes(transformed),metadata


def encrypt_mp4(clear: Path, destination: Path, *, key: bytes, kid: bytes,
                scheme: str='cenc', ffprobe: Path=Path('C:/ffmpeg/bin/ffprobe.exe')) -> None:
    """Encrypt the test H264/AAC MP4 with independent sample/box production."""
    assert scheme in {'cenc','cens','cbc1','cbcs'}
    assert len(key)==len(kid)==16
    probe=subprocess.run([str(ffprobe),'-v','error','-show_packets','-show_streams','-of','json',str(clear)],
                         capture_output=True,check=True,timeout=20,
                         creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
    facts=json.loads(probe.stdout)
    data=bytearray(clear.read_bytes())
    tracks={stream['index']: {'video':stream['codec_type']=='video','samples':[]} for stream in facts['streams']}
    for packet in facts['packets']:
        index=packet['stream_index']
        offset,size=int(packet['pos']),int(packet['size'])
        sequence=len(tracks[index]['samples'])
        iv=(index+1).to_bytes(8,'big')+sequence.to_bytes(8,'big')
        cipher,metadata=_encrypt(bytes(data[offset:offset+size]),key=key,iv=iv,scheme=scheme,video=tracks[index]['video'])
        data[offset:offset+size]=cipher
        tracks[index]['samples'].append(metadata)
    top=list(_boxes(bytes(data)))
    assert top[-1][0]==b'moov', 'fixture requires a final moov, preserving sample offsets'
    track_number=0
    def rewrite(kind,content,track=None):
        nonlocal track_number
        if kind==b'trak':
            track=tracks[track_number]
            track_number+=1
        if kind in {b'moov',b'trak',b'mdia',b'minf',b'stbl'}:
            output=b''.join(rewrite(child,payload,track) for child,payload in _boxes(content))
            if kind==b'stbl':
                output+=_box(b'senc',b'\0\0\0\2'+struct.pack('>I',len(track['samples']))+b''.join(track['samples']))
            return _box(kind,output)
        if kind==b'stsd':
            assert int.from_bytes(content[4:8],'big')==1
            descriptions=list(_boxes(content[8:]));assert len(descriptions)==1
            original,sample_entry=descriptions[0]
            assert original==(b'avc1' if track['video'] else b'mp4a')
            pattern=(0x19 if track['video'] else 0x10) if scheme in {'cens','cbcs'} else 0
            tenc=bytes([1 if pattern else 0,0,0,0,0,pattern,1,16])+kid
            sinf=_box(b'sinf',_box(b'frma',original)+_box(b'schm',b'\0'*4+scheme.encode()+struct.pack('>I',0x10000))+_box(b'schi',_box(b'tenc',tenc)))
            return _box(kind,content[:8]+_box(b'encv' if track['video'] else b'enca',sample_entry+sinf))
        return _box(kind,content)
    destination.write_bytes(b''.join(rewrite(kind,content) for kind,content in top))
