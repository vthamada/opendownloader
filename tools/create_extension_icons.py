"""Original OpenDownloader vector mark; deterministic SVG/PNG, stdlib only.

The rounded green square and pale downward arrow share one geometry below.
No downloaded artwork, fonts, renderer, or image-generation service is used.
"""
from __future__ import annotations
import binascii
from pathlib import Path
import struct
import zlib

PROJECT = Path(__file__).resolve().parents[1]
ARROW = ((58, 35), (70, 35), (70, 65), (86, 65), (64, 88), (42, 65), (58, 65))
GREEN = (38, 74, 62, 255)
PALE = (231, 240, 186, 255)
EDGE = (171, 202, 164, 255)


def rounded(x, y, inset, radius):
    left, right = inset, 128 - inset
    if not left <= x <= right or not left <= y <= right:
        return False
    cx = min(max(x, left + radius), right - radius)
    cy = min(max(y, left + radius), right - radius)
    return (x-cx)**2 + (y-cy)**2 <= radius**2


def polygon(x, y):
    inside = False
    previous = ARROW[-1]
    for current in ARROW:
        ax, ay = previous
        bx, by = current
        if (ay > y) != (by > y) and x < (bx-ax)*(y-ay)/(by-ay)+ax:
            inside = not inside
        previous = current
    return inside


def sample(x, y):
    if not rounded(x, y, 16, 24):
        return (0, 0, 0, 0)
    if not rounded(x, y, 18, 22):
        return EDGE
    return PALE if polygon(x, y) else GREEN


def png(width, height, pixel):
    """4x4 supersampling; premultiplied averaging preserves transparent edges."""
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            samples = [pixel(x+(sx+.5)/4, y+(sy+.5)/4)
                       for sy in range(4) for sx in range(4)]
            alpha = sum(value[3] for value in samples)
            rows.extend([round(sum(value[c]*value[3] for value in samples)/alpha)
                         if alpha else 0 for c in range(3)] + [round(alpha/16)])
    def chunk(kind, body):
        return struct.pack('>I', len(body))+kind+body+struct.pack('>I', binascii.crc32(kind+body)&0xffffffff)
    return (b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
            +chunk(b'IDAT', zlib.compress(bytes(rows), 9))+chunk(b'IEND', b''))


def main():
    icons = PROJECT/'browser-extension'/'icons'
    assets = PROJECT/'.cache'/'store-assets'
    icons.mkdir(exist_ok=True)
    assets.mkdir(parents=True, exist_ok=True)
    path = 'M '+' L '.join(f'{x} {y}' for x, y in ARROW)+' Z'
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">\n'
           '<rect x="16" y="16" width="96" height="96" rx="24" fill="#abcaa4"/>\n'
           '<rect x="18" y="18" width="92" height="92" rx="22" fill="#264a3e"/>\n'
           f'<path d="{path}" fill="#e7f0ba"/>\n</svg>\n')
    (icons/'opendownloader.svg').write_text(svg, encoding='utf-8', newline='\n')
    for size in (16, 32, 48, 128):
        (icons/f'icon-{size}.png').write_bytes(png(size, size, lambda x, y: sample(x*128/size, y*128/size)))
    (assets/'logo-300.png').write_bytes(png(300, 300, lambda x, y: sample(x*128/300, y*128/300)))
    def tile(x, y):
        mark = sample((x-124)/1.5, (y-44)/1.5)
        return mark if mark[3] else (17, 44, 37, 255)
    (assets/'promo-440x280.png').write_bytes(png(440, 280, tile))
    (assets/'ARTWORK.md').write_text(
        'Original OpenDownloader artwork generated by tools/create_extension_icons.py.\n'
        'logo-300.png: store logo; promo-440x280.png: promotional artwork, NOT a screenshot.\n'
        'Real browser screenshots remain pending. No third-party artwork or fonts.\n', encoding='utf-8', newline='\n')
    print(f'Generated original icons and store artwork: {icons}; {assets}')


if __name__ == '__main__':
    main()
